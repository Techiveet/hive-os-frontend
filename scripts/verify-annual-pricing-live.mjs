import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('annual-pricing-evidence',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const catalog=page.waitForResponse(r=>r.url().includes('/public/subscriptions/catalog')&&r.status()===200,{timeout:90000});
const home=await page.goto('https://hive.techiveet.com',{waitUntil:'domcontentloaded',timeout:60000});
const response=await catalog;const {data}=await response.json();
const discount=Number(data.billing_policy.yearly_discount_percent);
const expected=Object.values(data.plan_pricing).filter(p=>!p.is_disabled).map(p=>{const v=Math.round((Number(p.monthly_price_etb)*12*(1-discount/100)+Number.EPSILON)*100)/100;return 'ETB '+v.toLocaleString('en-US',{minimumFractionDigits:v%1?2:0,maximumFractionDigits:v%1?2:0})+'/year';});
for(const price of expected)await page.locator('#pricing').getByText(price,{exact:false}).first().waitFor({timeout:45000});
await page.locator('#pricing').screenshot({path:'annual-pricing-evidence/desktop.png'});
console.log('Desktop annual prices:',expected);
await page.setViewportSize({width:390,height:844});
for(const price of expected)assert.ok(await page.locator('#pricing').getByText(price,{exact:false}).first().isVisible());
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Mobile page overflow');
await page.locator('#pricing').screenshot({path:'annual-pricing-evidence/mobile.png'});
await page.goto('https://hive.techiveet.com/auth/signup',{waitUntil:'domcontentloaded',timeout:60000});
for(const price of expected)await page.getByText(price,{exact:false}).first().waitFor({timeout:45000});
await page.screenshot({path:'annual-pricing-evidence/signup.png',fullPage:true});
assert.equal(errors.length,0,JSON.stringify(errors));
console.log(JSON.stringify({home:home.status(),catalog:response.status(),discount,desktop:true,mobile:true,signup:true,pageErrors:errors}));
await browser.close();
